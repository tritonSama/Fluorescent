def write_header(file_path):
    with open(file_path, 'w') as f:
        f.write("#pragma once\n\n")
        f.write("#include <stdint.h>\n\n")

        f.write("static const uint32_t VERTEX_SHADER[] = {\n")
        for i in range(0, len(VERTEX_SHADER_SPIRV), 8):
            chunk = VERTEX_SHADER_SPIRV[i:i+8]
            f.write("    " + ", ".join(f"0x{word:08x}" for word in chunk) + ",\n")
        f.write("};\n\n")

        f.write("static const uint32_t FRAGMENT_SHADER[] = {\n")
        for i in range(0, len(FRAGMENT_SHADER_SPIRV), 8):
            chunk = FRAGMENT_SHADER_SPIRV[i:i+8]
            f.write("    " + ", ".join(f"0x{word:08x}" for word in chunk) + ",\n")
        f.write("};\n")

